def parse_spec() -> list[tuple[str, str, str]]:
    label_to_freq = {v: k for k, v in FREQUENCY_LABELS.items()}
    rows, category = [], None
    for line in SPEC.strip().splitlines():
        if line.startswith("### "):
            category = line[4:]
        elif line.startswith("- 【"):
            freq_label, title = line[3:].split("】", 1)
            rows.append((category, label_to_freq[freq_label], title))
    return rows


def actual() -> list[tuple[str, str, str]]:
    return [(TASK_TREE[t["category"]]["label"], t["frequency"], t["title"]) for t in INITIAL_TASKS]


def test_task_list_matches_spec_exactly():
    assert actual() == parse_spec()
    assert len(INITIAL_TASKS) == 54


def test_keys_unique_and_schedules_valid():
    keys = [t["key"] for t in INITIAL_TASKS]
    assert len(keys) == len(set(keys))
    for t in INITIAL_TASKS:
        if t["frequency"] == "weekly":
            assert t["weekdays"] and all(0 <= w <= 6 for w in t["weekdays"])
        if t["frequency"] == "monthly":
            assert (t["day_of_month"] is not None) != (t["nth_week"] is not None)
            assert all(1 <= m <= 12 for m in (t["months"] or []))
